def get_profile(name: str) -> CriteriaProfile:
    """Look up a registered :class:`CriteriaProfile` by name.

    Args:
        name: Key of :data:`CRITERIA_PROFILES`.

    Returns:
        The profile.

    Raises:
        KeyError: Unknown name; the message lists the available profiles.
    """
    try:
        return CRITERIA_PROFILES[name]
    except KeyError as exc:
        raise KeyError(
            f"unknown criteria profile {name!r}; available: {sorted(CRITERIA_PROFILES)}"
        ) from exc


@dataclass(frozen=True)
class CriteriaResult:
    """One evaluated acceptance-criterion row.

    Attributes:
        name: Criterion identifier.
        value: Measured value, or ``None`` when the input was not supplied.
        threshold: Human-readable threshold description.
        passed: Honest pass/fail; always ``False`` when not evaluated.
        evaluated: Whether a usable input was available to evaluate (a
            wave speed measured with a detector other than the profile's
            is present but not usable).
        detail: Optional explanatory note; for ``wave_speed`` it names the
            detector recipe behind the value. A row whose input some run did
            not record starts it with :data:`NOT_RECORDED`.
    """

    name: str
    value: float | None
    threshold: str
    passed: bool
    evaluated: bool
    detail: str = ""

    @property
    def status(self) -> CriterionStatus:
        """``PASS`` / ``FAIL`` when evaluated, else ``NOT RECORDED`` (the
        ``detail`` starts with :data:`NOT_RECORDED`) or ``NOT EVALUATED``.
        Neither of the last two is a pass."""
        if self.evaluated:
            return "PASS" if self.passed else "FAIL"
        return "NOT RECORDED" if self.detail.startswith(NOT_RECORDED) else "NOT EVALUATED"


def zero_collisions(counts: Sequence[int | None]) -> bool | None:
    """Whether a run set is collision-free, from its per-run collision counts.

    Args:
        counts: One entry per run: its ``meta.json["n_collisions"]``, or None
            when the run does not record the counter
            (``validation.battery.collision_count``).

    Returns:
        False when any run records a collision (whatever the others record);
        otherwise None when the set is empty or any run lacks the counter (not
        recorded is not zero); True only when every run records zero.
    """
    recorded = [c for c in counts if c is not None]
    if any(c > 0 for c in recorded):
        return False
    if not counts or len(recorded) < len(counts):
        return None
    return True


def _collision_row(counts: Sequence[int | None] | None) -> CriteriaResult:
    """The ``no_collisions`` row (module docstring, "Model integrity").

    Args:
        counts: Per-run collision counts (None for a run without the
            counter), or None when the caller supplied none.

    Returns:
        The row: FAIL (``value`` the total over the runs that record it),
        PASS (``value`` 0) or NOT RECORDED (``value`` None).
    """
    text = "zero SUMO collisions in every run, each run recording the counter"
    if counts is None:
        return CriteriaResult(
            name=NO_COLLISIONS,
            value=None,
            threshold=text,
            passed=False,
            evaluated=False,
            detail=f"{NOT_RECORDED}: no per-run collision counts supplied; "
            + NO_COLLISIONS_STANDARD,
        )
    recorded = [c for c in counts if c is not None]
    n_missing = len(counts) - len(recorded)
    total = sum(recorded)
    flag = zero_collisions(counts)
    if flag is None:
        why = (
            "no runs supplied"
            if not counts
            else f"{n_missing} of {len(counts)} run(s) carry no collision counter "
            "(meta.json n_collisions)"
        )
        return CriteriaResult(
            name=NO_COLLISIONS,
            value=None,
            threshold=text,
            passed=False,
            evaluated=False,
            detail=f"{NOT_RECORDED}: {why}; {NO_COLLISIONS_STANDARD}",
        )
    if flag:
        detail = f"no collision in {len(counts)} run(s); {NO_COLLISIONS_STANDARD}"
    else:
        n_with = sum(1 for c in recorded if c > 0)
        detail = (
            f"{total} collision(s) in {n_with} of {len(recorded)} run(s) that record the counter"
            + (f"; {n_missing} run(s) not recorded" if n_missing else "")
            + f"; {NO_COLLISIONS_STANDARD}"
        )
    return CriteriaResult(
        name=NO_COLLISIONS,
        value=float(total),
        threshold=text,
        passed=flag,
        evaluated=True,
        detail=detail,
    )


def zero_locks(flags: Sequence[bool | None]) -> bool | None:
    """Whether a run set is lock-free, from its per-run lock flags.

    Args:
        flags: One entry per run: whether it locked
            (``validation.locks.RunLocks.locked``), or None when the run
            carries neither file the detector reads.

    Returns:
        False when any run locked (whatever the others record); otherwise
        None when the set is empty or any run is not recorded (not recorded
        is not "no lock"); True only when every run is recorded and none
        locked.
    """
    if any(f is True for f in flags):
        return False
    if not flags or any(f is None for f in flags):
        return None
    return True


def _lock_row(flags: Sequence[bool | None] | None) -> CriteriaResult:
    """The ``no_locks`` row (module docstring, "Model integrity: no locks").

    Args:
        flags: Per-run lock flags (None for a run not recorded), or None
            when the caller supplied none.

    Returns:
        The row: FAIL (``value`` the number of locked runs), PASS (``value``
        0) or NOT RECORDED (``value`` None).
    """
    text = (
        f"no run locked (no queue standing without discharge for "
        f"{LOCK_MIN_DURATION_S / _S_PER_MIN:g} min or more), every run recorded"
    )
    if flags is None:
        return CriteriaResult(
            name=NO_LOCKS,
            value=None,
            threshold=text,
            passed=False,
            evaluated=False,
            detail=f"{NOT_RECORDED}: no per-run lock records supplied; " + NO_LOCKS_STANDARD,
        )
    recorded = [f for f in flags if f is not None]
    n_missing = len(flags) - len(recorded)
    n_locked = sum(1 for f in recorded if f)
    flag = zero_locks(flags)
    if flag is None:
        why = (
            "no runs supplied"
            if not flags
            else f"{n_missing} of {len(flags)} run(s) carry no lock record "
            "(neither edges.parquet nor vehicles.parquet)"
        )
        return CriteriaResult(
            name=NO_LOCKS,
            value=None,
            threshold=text,
            passed=False,
            evaluated=False,
            detail=f"{NOT_RECORDED}: {why}; {NO_LOCKS_STANDARD}",
        )
    if flag:
        detail = f"no lock in {len(flags)} run(s); {NO_LOCKS_STANDARD}"
    else:
        detail = (
            f"{n_locked} of {len(recorded)} recorded run(s) locked"
            + (f"; {n_missing} run(s) not recorded" if n_missing else "")
            + f"; {NO_LOCKS_STANDARD}"
        )
    return CriteriaResult(
        name=NO_LOCKS,
        value=float(n_locked),
        threshold=text,
        passed=flag,
        evaluated=True,
        detail=detail,
    )


def _not_evaluated(
    name: str, threshold: str, *, observations_supplied: bool = False
) -> CriteriaResult:
    """An unevaluated row, saying honestly *why* it could not be evaluated.

    Args:
        name: Criterion identifier.
        threshold: Human-readable threshold description.
        observations_supplied: For the two rows scored against an
            observations artifact: the artifact was supplied but produced no
            comparable window (no station pair, no window inside the
            measurement span, no observed cell). "Input not supplied" would
            be false, and would send the reader looking for an upload that
            is already there.

    Returns:
        The row, with ``evaluated=False``.
    """
    detail = (
        "not evaluated: observations supplied, no comparable window (see the observed-data block)"
        if observations_supplied
        else "not evaluated: input not supplied"
    )
    return CriteriaResult(
        name=name,
        value=None,
        threshold=threshold,
        passed=False,
        evaluated=False,
        detail=detail,
    )


def _grid_cell_present(
    cell: tuple[float, float], grid: Sequence[tuple[float, float]], tol: float = 1e-6
) -> bool:
    return any(
        math.isclose(cell[0], g[0], abs_tol=tol) and math.isclose(cell[1], g[1], abs_tol=tol)
        for g in grid
    )


def evaluate(
    profile: CriteriaProfile | None = None,
    *,
    geh_values: Sequence[float] | None = None,
    rmspe_value: float | None = None,
    wave_speed_kmh: float | None = None,
    wave_detector: WaveDetector | None = None,
    ring_emergence: bool | None = None,
    ring_dampening: bool | None = None,
    n_seeds: int | None = None,
    sweep_grid: Sequence[tuple[float, float]] | None = None,
    observations_supplied: bool = False,
    collision_counts: Sequence[int | None] | None = None,
    lock_flags: Sequence[bool | None] | None = None,
) -> list[CriteriaResult]:
    """Evaluate acceptance criteria against measured values.

    Every check in the profile yields exactly one row. A check whose input
    is ``None`` (or NaN) is reported with ``evaluated=False`` (respectively
    a failing NaN value) rather than silently dropped — an unevaluated
    criterion is never a pass (CLAUDE.md §0.1).

    Args:
        profile: Threshold profile; ``None`` uses ``fhwa_default``
            (:class:`CriteriaProfile` defaults).
        geh_values: Per-link-hour GEH statistics (e.g.
            :func:`validation.metrics.link_hour_geh` ``.geh``).
        rmspe_value: Segment-speed RMSPE as a fraction.
        wave_speed_kmh: Emergent backward wave-front speed magnitude [km/h]
            (positive), measured with the profile's ``wave_detector`` —
            ``profile.wave_detector.measure(field).speed_kmh``.
        wave_detector: The detector that produced ``wave_speed_kmh``. When it
            is not the profile's, the row is reported as not evaluated (the
            value is kept, with both recipes named); when omitted the row
            notes that the caller did not state its detector.
        ring_emergence: Whether the Sugiyama ring emergence benchmark passed
            (``validation.ring_benchmark``).
        ring_dampening: Whether the single-AV dampening benchmark passed.
        n_seeds: Number of replicate seeds behind the reported metrics.
        sweep_grid: ``(penetration, compliance)`` cells of the published
            sensitivity sweep, as fractions. Pass only cells whose metrics
            carry replicate CIs (CLAUDE.md §7.1 "published with CIs") — the
            row checks presence of every required cell, not the CIs.
        observations_supplied: Whether an observations artifact was supplied
            for the two rows scored against one (``link_flows_geh``,
            ``speeds_rmspe``). With ``geh_values`` / ``rmspe_value`` still
            ``None`` the rows stay unevaluated, but say that the artifact
            yielded no comparable window rather than that no input was given.
        collision_counts: One entry per run of the set: its
            ``meta.json["n_collisions"]``, or None when the run does not
            record it (``validation.battery.collision_count``). Feeds the
            ``no_collisions`` row every profile carries (last): PASS only
            when every run records zero, FAIL on any collision, otherwise
            NOT RECORDED (also when ``None`` is passed: no counts supplied).
        lock_flags: One entry per run of the set: whether it locked
            (``validation.locks.RunLocks.locked``), or None when the run is
            not recorded (``validation.locks.lock_flags``). Feeds the
            ``no_locks`` row every profile carries (after ``no_collisions``,
            last): PASS only when every run is recorded and none locked,
            FAIL when any run locked, otherwise NOT RECORDED (also when
            ``None`` is passed: no records supplied).

    Returns:
        One :class:`CriteriaResult` per profile check, in table order.
    """
    p = profile if profile is not None else CriteriaProfile()
    rows: list[CriteriaResult] = []

    cmp = ">=" if p.geh_pass_inclusive else ">"
    geh_threshold_text = (
        f"GEH < {p.geh_threshold:g} for {cmp} {p.geh_pass_fraction:.0%} of link-hour comparisons"
    )
    if geh_values is None:
        rows.append(
            _not_evaluated(
                "link_flows_geh",
                geh_threshold_text,
                observations_supplied=observations_supplied,
            )
        )
    elif len(geh_values) == 0:
        rows.append(
            CriteriaResult(
                name="link_flows_geh",
                value=math.nan,
                threshold=geh_threshold_text,
                passed=False,
                evaluated=True,
                detail="no comparisons supplied",
            )
        )
    else:
        frac = sum(1 for g in geh_values if g < p.geh_threshold) / len(geh_values)
        passed = frac >= p.geh_pass_fraction if p.geh_pass_inclusive else frac > p.geh_pass_fraction
        rows.append(
            CriteriaResult(
                name="link_flows_geh",
                value=frac,
                threshold=geh_threshold_text,
                passed=passed,
                evaluated=True,
                detail=f"fraction of comparisons with GEH < {p.geh_threshold:g}",
            )
        )

    if p.rmspe_max is not None:
        rmspe_text = f"segment-speed RMSPE <= {p.rmspe_max:.0%}"
        if rmspe_value is None:
            rows.append(
                _not_evaluated(
                    "speeds_rmspe",
                    rmspe_text,
                    observations_supplied=observations_supplied,
                )
            )
        else:
            rows.append(
                CriteriaResult(
                    name="speeds_rmspe",
                    value=rmspe_value,
                    threshold=rmspe_text,
                    passed=bool(rmspe_value <= p.rmspe_max),
                    evaluated=True,
                )
            )

    lo, hi = p.wave_speed_band_kmh
    wave_text = f"backward wave speed in [{lo:g}, {hi:g}] km/h (emergent, unseeded)"
    detector_text = f"detector: {p.wave_detector.describe()}"
    if wave_speed_kmh is None:
        rows.append(_not_evaluated("wave_speed", wave_text))
    elif wave_detector is not None and wave_detector != p.wave_detector:
        rows.append(
            CriteriaResult(
                name="wave_speed",
                value=wave_speed_kmh,
                threshold=wave_text,
                passed=False,
                evaluated=False,
                detail=(
                    f"not evaluated: value measured with {wave_detector.describe()}; "
                    f"profile requires {p.wave_detector.describe()}"
                ),
            )
        )
    else:
        in_band = bool(lo <= wave_speed_kmh <= hi)  # NaN compares False
        notes = [detector_text]
        if wave_detector is None:
            notes.append("caller did not state which detector produced the value")
        if not math.isfinite(wave_speed_kmh):
            notes.append("no backward wave detected")
        rows.append(
            CriteriaResult(
                name="wave_speed",
                value=wave_speed_kmh,
                threshold=wave_text,
                passed=in_band,
                evaluated=True,
                detail="; ".join(notes),
            )
        )

    if p.require_ring_emergence:
        text = "Sugiyama ring emergence benchmark reproduced"
        if ring_emergence is None:
            rows.append(_not_evaluated("ring_emergence", text))
        else:
            rows.append(
                CriteriaResult(
                    name="ring_emergence",
                    value=float(ring_emergence),
                    threshold=text,
                    passed=bool(ring_emergence),
                    evaluated=True,
                )
            )

    if p.require_ring_dampening:
        text = "Stern single-AV dampening benchmark reproduced"
        if ring_dampening is None:
            rows.append(_not_evaluated("ring_dampening", text))
        else:
            rows.append(
                CriteriaResult(
                    name="ring_dampening",
                    value=float(ring_dampening),
                    threshold=text,
                    passed=bool(ring_dampening),
                    evaluated=True,
                )
            )

    seeds_text = f"n_seeds >= {p.min_seeds}"
    if n_seeds is None:
        rows.append(_not_evaluated("n_seeds", seeds_text))
    else:
        rows.append(
            CriteriaResult(
                name="n_seeds",
                value=float(n_seeds),
                threshold=seeds_text,
                passed=n_seeds >= p.min_seeds,
                evaluated=True,
            )
        )

    if p.require_sensitivity_grid:
        pens = "{" + ", ".join(f"{v:.0%}" for v in p.required_penetrations) + "}"
        comps = "{" + ", ".join(f"{v:.0%}" for v in p.required_compliances) + "}"
        grid_text = f"penetration {pens} x compliance {comps} grid published with CIs"
        if sweep_grid is None:
            rows.append(_not_evaluated("sensitivity_grid", grid_text))
        else:
            required = [
                (pen, comp) for pen in p.required_penetrations for comp in p.required_compliances
            ]
            missing = [c for c in required if not _grid_cell_present(c, sweep_grid)]
            n_present = len(required) - len(missing)
            detail = f"{n_present}/{len(required)} required cells present"
            if missing:
                detail += "; missing: " + ", ".join(
                    f"({pen:.0%}, {comp:.0%})" for pen, comp in missing
                )
            rows.append(
                CriteriaResult(
                    name="sensitivity_grid",
                    value=n_present / len(required),
                    threshold=grid_text,
                    passed=not missing,
                    evaluated=True,
                    detail=detail,
                )
            )

    # Model integrity, in every profile (2026-10-04, WP-98; locks 2026-10-07).
    rows.append(_collision_row(collision_counts))
    rows.append(_lock_row(lock_flags))
    return rows
