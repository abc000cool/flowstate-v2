"""Acceptance criteria (CLAUDE.md §7.1) as data, not prose.

Encodes acceptance tables as :class:`CriteriaProfile` records held in the
:data:`CRITERIA_PROFILES` registry (``get_profile(name)``) and evaluates
supplied measurements into honest pass/fail rows — no rounding games; a
missing input is reported as *not evaluated and failing* (CLAUDE.md §0.1).

Every profile carries a ``source`` string stating exactly which document,
section and table its numbers were transcribed from, what was verified in
this repository's session and how, and which fields are FlowState's own
conventions rather than the document's. Read those strings before quoting a
profile in a report. Summary of the verification (2026-09-03):

* **FHWA Traffic Analysis Toolbox Vol. III, 2004** (FHWA-HRT-04-040), §5.6
  "Calibration Targets", verified on the HTML edition at
  https://ops.fhwa.dot.gov/trafficanalysistools/tat_vol3/sect5.htm, where the
  Wisconsin DOT freeway calibration table is captioned "Table 4" (attributed
  to WisDOT District 2, Paramics Calibration and Validation Guidelines,
  Technical Report I-33, June 2002). Rows: individual link flows within 15%
  (700–2,700 veh/h), within 100 veh/h (< 700), within 400 veh/h (> 2,700),
  each for > 85% of cases; sum of all link flows within 5%; **GEH < 5 for
  individual link flows in > 85% of cases**; GEH < 4 for the sum; journey
  times within 15% (or 1 min if higher) for > 85% of cases; visual audits to
  the analyst's satisfaction. CLAUDE.md §7.1 refers to this as "Table 5";
  the HTML edition numbers it Table 4 — the PDF numbering was not checked.
* **FHWA Traffic Analysis Toolbox Vol. III, 2019 update** (FHWA-HOP-18-036),
  Chapter 5 "Model Calibration", verified at
  https://ops.fhwa.dot.gov/publications/fhwahop18036/chapter5.htm: it
  contains **no GEH or 85% target**. It derives project-specific acceptance
  envelopes from observed-data variability (Criteria I–IV: 95% of simulated
  outputs inside the time-variant envelope; two-thirds inside the
  representative-day band; bounded dynamic absolute and systematic error)
  and states "The analyst does not need to calibrate multiple model runs
  generated by varying the random number seeds." The fixed GEH/85% wording
  that CLAUDE.md attributes to "FHWA-HOP-18-036 usage" is therefore the
  2004 edition's (and its DOT descendants'), not the 2019 text.
* **Oregon DOT, Protocol for VISSIM Simulation (June 2011)**, read from the
  PDF at https://www.oregon.gov/odot/Planning/Documents/APMv2_Add15A.pdf,
  §6.1 Tables 6-1/6-2, §6.2, §6.3 Table 6-3, §6.9.
* **TxDOT Traffic and Safety Analysis Procedures Manual, Chapter 13
  "Microsimulation Analysis"**, §13.5.2 "Acceptability Criteria" and
  §13.5.2.3 "Throughput", read at
  https://www.txdot.gov/manuals/des/tsp/chapter-13-microsimulation-analysis/13-5-calibration/13-5-2-acceptability-criteria.html
  (Tables 13-4 and 13-5). The travel-time criteria of §13.5.2.2 (Table
  13-3) are equations published as images and could not be read.

The segment-speed RMSPE bound, the emergent backward wave-speed band, the
ring benchmarks, the ≥ 20-seed rule and the penetration × compliance grid are
FlowState requirements from CLAUDE.md §7.1/§0.6, present in every profile and
labeled as such in ``source``; no DOT document above prescribes them.

**Model integrity: no SUMO collisions** (2026-10-04, owner decision, WP-98).
Every profile's results end with a ``no_collisions`` row, evaluated from the
per-run collision counts (``meta.json["n_collisions"]``, read by
``validation.battery.collision_count``): PASS only when every run records the
counter and the total is zero; FAIL when any run records a collision; NOT
RECORDED — never a pass, never a zero — when no failure is recorded but some
run lacks the counter or no counts were supplied (:func:`zero_collisions`).
A collision in a car-following simulation is a model defect, not a traffic
outcome (CLAUDE.md §3.3: controllers must not be able to command
collisions). It is a FlowState internal standard, not an FHWA or DOT
criterion, and its row says so. A NOT RECORDED row has ``evaluated=False``
and a ``detail`` starting with :data:`NOT_RECORDED`; :attr:`CriteriaResult.
status` names the four outcomes.

**Model integrity: no locks** (2026-10-07, docs/I94_COLLAPSE_DIAGNOSIS.md
§7). Every profile's results end, after ``no_collisions``, with a
``no_locks`` row, evaluated from the per-run lock records of
:mod:`validation.locks` (``RunLocks.locked``: True when vehicles stood with
no discharge past a point for at least
:data:`validation.locks.LOCK_MIN_DURATION_S` with a queue behind it):
PASS only when every run is recorded and none locked; FAIL when any run
locked; NOT RECORDED when no run locked but some run carries neither file the
detector reads (``edges.parquet``, ``vehicles.parquet``) or no records were
supplied (:func:`zero_locks`). A permanent standstill in a simulation without
teleporting is a model defect (no release rule reaches the vehicle at its
front), not a traffic outcome; every metric of a locked run includes the
vehicles trapped behind it. It is a FlowState internal standard, not an FHWA
or DOT criterion, and its row says so.

The wave-speed row's number depends on the detector that produced it, so
every profile names its detector (``wave_detector``, a
:class:`validation.waves.WaveDetector`) and the evaluated row records that
recipe in its ``detail``. The default is ``stack``: on the planted-stripe
benchmark of ``validation.waves`` it is the only registered detector that
recovers the planted speed at every congested fraction from 0.3 to 0.95
(16.0–16.1 km/h for 16 planted) — the ``standard`` 40 km/h detector finds no
backward front at any of them because a congested background is one
component whose front is the standing queue tail, ``relative`` finds none
below 90% congestion, and ``stripe`` is biased by up to 4.4 km/h when the
background sits near its own 25 km/h threshold. Callers state the detector
they used via ``evaluate(..., wave_detector=...)``; a value measured with a
different recipe is reported as not evaluated rather than scored.
"""

