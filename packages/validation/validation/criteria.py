@dataclass(frozen=True)
class CriteriaProfile:
    """One named set of acceptance thresholds (CLAUDE.md §7.1 table).

    The defaults reproduce the ``fhwa_default`` profile, so
    ``CriteriaProfile()`` is that profile.

    Attributes:
        name: Profile identifier (recorded in reports).
        source: Provenance: document, section, table, what was verified and
            how, and which fields are FlowState conventions. Never empty.
        geh_threshold: Per-comparison GEH acceptance bound (strict ``<``).
        geh_pass_fraction: Minimum fraction of link-hour comparisons that
            must satisfy the GEH bound.
        geh_pass_inclusive: Whether the fraction test is ``>=`` (True) or
            strict ``>`` (False, the 2004 FHWA table's "> 85% of cases").
        rmspe_max: Maximum segment-speed RMSPE as a fraction (inclusive), or
            ``None`` when the profile's source defines no RMSPE bound — the
            ``speeds_rmspe`` row is then not produced.
        wave_speed_band_kmh: Acceptance band for the emergent backward
            wave-front speed magnitude [km/h], inclusive on both ends.
        wave_detector: The :class:`validation.waves.WaveDetector` recipe
            that must produce ``wave_speed_kmh`` for this profile; its
            description is written into the evaluated row. Default
            ``validation.waves.STACK_DETECTOR`` — see the module docstring
            for the benchmark evidence. ``validation.report.generate_report``
            measures the criterion with this detector, on fields binned at
            this detector's own bins, and states it to :func:`evaluate`; the
            ``wave_speed_kmh`` of ``validation.metrics.compute_metrics`` is a
            separate ``standard``-detector diagnostic that appears in the
            report's metric tables and is never scored as this row.
        min_seeds: Minimum replicate count for headline reporting.
        require_ring_emergence: Include the Sugiyama ring emergence check.
        require_ring_dampening: Include the Stern single-AV dampening check.
        require_sensitivity_grid: Include the penetration × compliance grid
            check (CLAUDE.md §7.1 "Sensitivity" row).
        required_penetrations: Penetration levels the grid must contain.
        required_compliances: Compliance levels the grid must contain.
    """

    name: str = "fhwa_default"
    source: str = FHWA_DEFAULT_SOURCE
    geh_threshold: float = 5.0
    geh_pass_fraction: float = 0.85
    geh_pass_inclusive: bool = True
    rmspe_max: float | None = 0.15
    wave_speed_band_kmh: tuple[float, float] = field(default=WAVE_SPEED_BAND_KMH)
    wave_detector: WaveDetector = STACK_DETECTOR
    min_seeds: int = 20
    require_ring_emergence: bool = True
    require_ring_dampening: bool = True
    require_sensitivity_grid: bool = True
    required_penetrations: tuple[float, ...] = REQUIRED_PENETRATIONS
    required_compliances: tuple[float, ...] = REQUIRED_COMPLIANCES

    def __post_init__(self) -> None:
        if not self.source.strip():
            raise ValueError(f"profile {self.name!r} needs a non-empty source")
        if not 0.0 < self.geh_pass_fraction <= 1.0:
            raise ValueError(f"geh_pass_fraction must be in (0, 1], got {self.geh_pass_fraction}")


